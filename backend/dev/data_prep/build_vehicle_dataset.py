"""Builds a single-class vehicle detection dataset from a hand-corrected pass.

Labels come from the makesense.ai export zip named by --zip. The COCO bootstrap
labels inside the --src bundle are superseded and are never read. Nothing in
--src is written.

The default split is by capture day, not by frame. Frames from one day share
lighting, weather and largely the same parked cars, so a random split would put
near duplicates on both sides and inflate the validation metric. The bundle's own
images/{train,val,test} division is the bootstrap's split and is ignored here for
the same reason.

--split test emits every frame as a single test split instead, for a lot held out
from a detector trained on another lot.
"""

import argparse
import json
import re
import shutil
from collections import defaultdict
from pathlib import Path
from zipfile import ZipFile

import cv2

BANDS = [("night", 0, 20), ("dusk", 20, 60), ("overcast", 60, 110), ("bright", 110, 256)]

# Capture filenames come in three shapes across the lots in data/. Only the date
# is needed, as the split key.
_DATE_PATTERNS = (
    re.compile(r"^(\d{4})-(\d{2})-(\d{2})[ _]"),   # 2026-03-10_1229, 2026-02-20 08_05_58
    re.compile(r"^IMG_(\d{4})(\d{2})(\d{2})_"),    # IMG_20260625_105448, IMG_20260520_195652_294
)


def band(lum):
    return next(name for name, lo, hi in BANDS if lo <= lum < hi)


def capture_date(stem):
    """Returns YYYY-MM-DD, or raises on a filename shape not listed above.

    Raising matters. A slice or a permissive fallback that returns the wrong
    substring groups unrelated frames under one pseudo-day, and the split then
    runs to completion on nonsense groups instead of failing.
    """
    for pattern in _DATE_PATTERNS:
        m = pattern.match(stem)
        if m:
            return "-".join(m.groups())
    raise ValueError(f"unrecognised capture filename: {stem!r}")


def parse_args():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--src", type=Path, required=True,
                   help="bundle directory produced by the vehicle bootstrap")
    p.add_argument("--zip", type=Path, required=True, dest="zip_path",
                   help="corrected makesense export zip")
    p.add_argument("--out", type=Path, required=True,
                   help="destination dataset directory, must not exist")
    p.add_argument("--split", choices=("day", "test"), default="day",
                   help="day: day-level train/val split. test: one test split, no train/val")
    return p.parse_args()


def readme(dst, src, zip_path, args, split_of_day, days, lum, labels, size, counts):
    n_labelled, empty_keep, night_exclude = counts
    n_sampled = n_labelled + len(empty_keep) + len(night_exclude)
    total = sum(len(v) for v in days.values())

    parts = [f"""# Vehicle detection dataset

Single class (`vehicle`), {total} frames at {size}, YOLO format.
Generated by `backend/dev/data_prep/build_vehicle_dataset.py`. Do not edit by hand.

## Where the labels came from

{n_sampled} frames were sampled from the camera archive and pre-labelled with stock
COCO YOLO weights, then corrected by hand in makesense.ai. The corrected export is
`{zip_path.as_posix()}` and it is the only source of boxes used here.

The COCO bootstrap labels in `{(src / 'labels').as_posix()}` are superseded. They are
the uncorrected machine output and are not read by the build script.
"""]

    if empty_keep or night_exclude:
        parts.append(f"""
## Frames without a label file

{n_labelled} of the {n_sampled} frames came back with a label file. The remaining
{len(empty_keep) + len(night_exclude)} were inspected and fall into two groups.
""")
    if empty_keep:
        parts.append(f"""
{len(empty_keep)} are genuinely empty daylight lots. They are included with empty `.txt`
files, as real negatives that help suppress false positives:

{chr(10).join('- `' + s + '`' for s in empty_keep)}
""")
    if night_exclude:
        n_night_labelled = sum(1 for s in labels if lum[s] < 20 and labels[s])
        parts.append(f"""
{len(night_exclude)} are night frames that do contain vehicles the annotator could not
see in the image. They are excluded from the dataset entirely and appear in no split:

{chr(10).join('- `' + s + '`' for s in night_exclude)}

They are excluded because a COCO pass at confidence 0.05 finds one to six vehicles
in most of them. Labelling them empty would teach the detector that vehicles at
night are background. That would undo the hand correction done on the
{n_night_labelled} night frames that are properly labelled. The absent label file
records annotator visibility, not an empty lot.

Final size: {n_labelled} labelled + {len(empty_keep)} empty = {total} frames.
""")

    if args.split == "day":
        val_days = [d for d in sorted(split_of_day) if split_of_day[d] == "val"]
        train_days = [d for d in sorted(split_of_day) if split_of_day[d] == "train"]
        n_val = sum(len(days[d]) for d in val_days)
        n_train = sum(len(days[d]) for d in train_days)
        parts.append(f"""
## Split

The split is by capture day, not by frame. Frames from one day share lighting,
weather and largely the same parked cars, so a random split would place near
duplicates on both sides of the split and inflate the validation metric. Whole
days are assigned, so no day contributes to both splits. The bundle's own
train/val/test division is the bootstrap's split and is not carried through.

Days are walked in date order. A day goes to val whenever val is below its 20%
share. This spreads validation across the whole capture period.

- train: {len(train_days)} days, {n_train} frames ({n_train / total:.0%})
- val: {len(val_days)} days, {n_val} frames ({n_val / total:.0%})

Val days: {", ".join(val_days)}

Train days: {", ".join(train_days)}

Both splits contain night frames (mean luminance below 20), which is the hard
case for this camera. A val set without night frames would not measure it.
""")
    else:
        parts.append(f"""
## Split

Every frame is in one `test` split. This lot is held out to evaluate a detector
trained on another lot, so there is no train/val division. `dataset.yaml` points
its `train:` and `val:` keys at the same test images, because Ultralytics will not
load a yaml that omits them. Nothing here is meant to be trained on.

- test: {len(days)} days, {total} frames

Night frames (mean luminance below 20): {sum(1 for s in lum if lum[s] < 20)}.
""")

    (dst / "README.md").write_text("".join(parts), encoding="utf-8")


def main(args):
    src, dst, zip_path = args.src, args.out, args.zip_path
    splits = ("train", "val") if args.split == "day" else ("test",)

    # 0. Frames, resolved recursively. The bundle keeps them under
    # images/{train,val,test}/, which is its own split, so only the stem matters.
    img_of = {}
    for path in sorted((src / "images").rglob("*.jpg")):
        assert path.stem not in img_of, f"stem appears in two image subdirectories: {path.stem}"
        img_of[path.stem] = path

    # Per-run frame lists. Missing file means neither list applies to this lot.
    frames_file = src / "build_frames.json"
    conf = json.loads(frames_file.read_text(encoding="utf-8")) if frames_file.exists() else {}
    empty_keep = conf.get("empty_keep", [])
    night_exclude = conf.get("night_exclude", [])

    # 1. Labels, straight from the export zip.
    labels = {}
    with ZipFile(zip_path) as z:
        for name in z.namelist():
            if name.endswith(".txt"):
                text = z.read(name).decode("utf-8")
                lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
                labels[Path(name).stem] = lines
    n_labelled = len(labels)
    for stem in empty_keep:
        labels[stem] = []

    overlap = sorted(set(labels) & set(night_exclude))
    assert not overlap, f"excluded night frames present in the label set: {overlap}"

    missing = sorted(s for s in labels if s not in img_of)
    assert not missing, f"labels without an image: {missing}"

    # 2. Luminance per frame, used for the split guard and the report.
    lum = {}
    for stem in labels:
        img = cv2.imread(str(img_of[stem]), cv2.IMREAD_GRAYSCALE)
        lum[stem] = float(img.mean())

    # 3. Split. Days are walked in date order and handed to val whenever val sits
    # below its 20% share, which spreads val across the whole capture period
    # instead of clustering it in one season.
    days = defaultdict(list)
    for stem in labels:
        days[capture_date(stem)].append(stem)

    if args.split == "day":
        split_of_day, val_frames, seen = {}, 0, 0
        for day in sorted(days):
            n = len(days[day])
            to_val = val_frames < 0.2 * seen
            split_of_day[day] = "val" if to_val else "train"
            val_frames += n if to_val else 0
            seen += n

        for name in splits:
            nights = [s for d, sp in split_of_day.items() if sp == name
                      for s in days[d] if lum[s] < 20]
            assert nights, f"{name} split has no night frames"
    else:
        split_of_day = {day: "test" for day in days}

    # 4. Write the dataset. mkdir refuses an existing directory by design.
    for sp in splits:
        (dst / "images" / sp).mkdir(parents=True)
        (dst / "labels" / sp).mkdir(parents=True)

    for day, sp in split_of_day.items():
        for stem in days[day]:
            shutil.copy2(img_of[stem], dst / "images" / sp / f"{stem}.jpg")
            body = "".join(f"{ln}\n" for ln in labels[stem])
            (dst / "labels" / sp / f"{stem}.txt").write_text(body, encoding="utf-8")

    if splits == ("test",):
        # check_det_dataset refuses any yaml without train and val keys, even when
        # a different split is the one being scored. Alias all three onto the test
        # images so the yaml loads at all. Nothing trains on a held-out lot.
        split_lines = "".join(f"{sp}: images/test\n" for sp in ("train", "val", "test"))
    else:
        split_lines = "".join(f"{sp}: images/{sp}\n" for sp in splits)

    (dst / "dataset.yaml").write_text(
        f"path: {dst.resolve()}\n"
        + split_lines
        + "nc: 1\n"
        "names: [vehicle]\n",
        encoding="utf-8",
    )

    h, w = cv2.imread(str(next(iter(img_of.values())))).shape[:2]
    readme(dst, src, zip_path, args, split_of_day, days, lum, labels,
           f"{w}x{h}", (n_labelled, empty_keep, night_exclude))

    # 5. Validation over what was actually written.
    print(f"=== {dst} ===")
    bad = []
    boxes = {sp: 0 for sp in splits}
    for sp in splits:
        for txt in sorted((dst / "labels" / sp).glob("*.txt")):
            for i, ln in enumerate(txt.read_text().splitlines(), 1):
                if not ln.strip():
                    continue
                parts = ln.split()
                ok = len(parts) == 5 and parts[0] == "0"
                if ok:
                    vals = [float(p) for p in parts[1:]]
                    ok = all(0.0 < v < 1.0 for v in vals)
                if not ok:
                    bad.append(f"{sp}/{txt.name}:{i} {ln!r}")
                boxes[sp] += 1
    print(f"label format 0 xc yc w h, all floats strictly in (0,1): "
          f"{'PASS' if not bad else 'FAIL ' + str(bad[:5])}")

    pair_err = []
    for sp in splits:
        imgs = {p.stem for p in (dst / "images" / sp).glob("*.jpg")}
        lbls = {p.stem for p in (dst / "labels" / sp).glob("*.txt")}
        pair_err += [f"{sp}: image without label {s}" for s in sorted(imgs - lbls)]
        pair_err += [f"{sp}: label without image {s}" for s in sorted(lbls - imgs)]
    print(f"image/label pairing both ways: {'PASS' if not pair_err else 'FAIL ' + str(pair_err)}")

    written = {p.stem for sp in splits for p in (dst / "images" / sp).glob("*.jpg")}
    leaked = sorted(set(night_exclude) & written)
    print(f"{len(night_exclude)} excluded night frames absent from output: "
          f"{'PASS' if not leaked else 'FAIL ' + str(leaked)}")

    empt = []
    for stem in empty_keep:
        hits = [p for sp in splits if (p := dst / "labels" / sp / f"{stem}.txt").exists()]
        if len(hits) != 1 or hits[0].stat().st_size != 0:
            empt.append(stem)
    print(f"{len(empty_keep)} empty-lot frames present with empty label files: "
          f"{'PASS' if not empt else 'FAIL ' + str(empt)}")

    # 6. Report.
    total = len(written)
    print(f"\nframes {total}   boxes {sum(boxes.values())}   "
          f"boxes/frame {sum(boxes.values()) / total:.2f}")
    for sp in splits:
        n = len(list((dst / "images" / sp).glob("*.jpg")))
        print(f"{sp}: {n} frames ({n / total:.0%})   {boxes[sp]} boxes")

    print("\nluminance bands (frames / boxes)")
    print(f"{'band':<10}" + "".join(f"{sp:>16}" for sp in splits))
    for name, lo, hi in BANDS:
        cells = []
        for sp in splits:
            stems = [p.stem for p in (dst / "images" / sp).glob("*.jpg") if lo <= lum[p.stem] < hi]
            b = sum(len(labels[s]) for s in stems)
            cells.append(f"{len(stems)} / {b}")
        print(f"{name:<10}" + "".join(f"{c:>16}" for c in cells))

    print("\nday assignment")
    for day in sorted(split_of_day):
        stems = days[day]
        nights = sum(1 for s in stems if lum[s] < 20)
        print(f"  {day}  {split_of_day[day]:<6} {len(stems):>2} frames  "
              f"{sum(len(labels[s]) for s in stems):>3} boxes  {nights} night")

    return split_of_day, days, lum, labels


if __name__ == "__main__":
    main(parse_args())
